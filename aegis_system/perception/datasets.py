NSL_FEATURES = [
    "duration", "protocol_type", "service", "flag", "src_bytes", "dst_bytes", "land", "wrong_fragment", "urgent",
    "hot", "num_failed_logins", "logged_in", "num_compromised", "root_shell", "su_attempted", "num_root",
    "num_file_creations", "num_shells", "num_access_files", "num_outbound_cmds", "is_host_login",
    "is_guest_login", "count", "srv_count", "serror_rate", "srv_serror_rate", "rerror_rate", "srv_rerror_rate",
    "same_srv_rate", "diff_srv_rate", "srv_diff_host_rate", "dst_host_count", "dst_host_srv_count",
    "dst_host_same_srv_rate", "dst_host_diff_srv_rate", "dst_host_same_src_port_rate",
    "dst_host_srv_diff_host_rate", "dst_host_serror_rate", "dst_host_srv_serror_rate", "dst_host_rerror_rate",
    "dst_host_srv_rerror_rate",
]
NSL_CATEGORICAL = ["protocol_type", "service", "flag"]
NSL_NUMERIC = [f for f in NSL_FEATURES if f not in NSL_CATEGORICAL]
# Traffic-shape features an attacker can change without breaking the attack; the
# protocol, service, flag and host-history rates stay fixed in the FGSM experiment.
NSL_MUTABLE = ["duration", "src_bytes", "dst_bytes", "count", "srv_count", "dst_host_count", "dst_host_srv_count"]

CATEGORIES = ("normal", "dos", "probe", "r2l", "u2r")
# Attack name -> category. Includes the attacks that only appear in KDDTest+.
ATTACK_CATEGORY = {
    "normal": "normal",
    **{a: "dos" for a in ["back", "land", "neptune", "pod", "smurf", "teardrop", "apache2", "mailbomb",
                          "processtable", "udpstorm"]},
    **{a: "probe" for a in ["ipsweep", "nmap", "portsweep", "satan", "mscan", "saint"]},
    **{a: "r2l" for a in ["ftp_write", "guess_passwd", "imap", "multihop", "phf", "spy", "warezclient",
                          "warezmaster", "named", "sendmail", "snmpgetattack", "snmpguess", "worm", "xlock",
                          "xsnoop"]},
    **{a: "u2r" for a in ["buffer_overflow", "loadmodule", "perl", "rootkit", "httptunnel", "ps", "sqlattack",
                          "xterm"]},
}


def nsl_kdd_available(data_dir: Union[str, Path, None] = None) -> bool:
    d = Path(data_dir or DATA_DIR)
    return (d / "KDDTrain+.txt").exists() and (d / "KDDTest+.txt").exists()


def load_nsl_kdd(
    split: str = "train",
    data_dir: Union[str, Path, None] = None,
    sample: Optional[int] = None,
    seed: int = 0,
) -> Tuple[pd.DataFrame, pd.Series]:
    """Features and category labels for KDDTrain+ ("train") or KDDTest+ ("test").

    sample draws a stratified subsample of that many rows (every category keeps at
    least one row when the split has one).
    """
    name = {"train": "KDDTrain+.txt", "test": "KDDTest+.txt"}[split]
    path = Path(data_dir or DATA_DIR) / name
    if not path.exists():
        raise FileNotFoundError(f"{path} not found. Run `python scripts/fetch_nsl_kdd.py` first.")
    df = pd.read_csv(path, header=None, names=NSL_FEATURES + ["attack", "difficulty"])
    unknown = set(df["attack"]) - set(ATTACK_CATEGORY)
    if unknown:
        raise ValueError(f"Unmapped attack names in {name}: {sorted(unknown)}")
    y = df["attack"].map(ATTACK_CATEGORY).rename("category")
    X = df[NSL_FEATURES]
    if sample is not None and sample < len(df):
        X, y = stratified_sample(X, y, sample, seed)
    return X.reset_index(drop=True), y.reset_index(drop=True)


def stratified_sample(X: pd.DataFrame, y: pd.Series, n: int, seed: int = 0) -> Tuple[pd.DataFrame, pd.Series]:
    """About n rows with the class proportions of y, keeping at least one row per class."""
    rng = np.random.default_rng(seed)
    idx = []
    for cls, rows in y.groupby(y).groups.items():
        rows = np.asarray(rows)
        k = max(1, int(round(n * len(rows) / len(y))))
        idx.extend(rng.choice(rows, size=min(k, len(rows)), replace=False))
    idx = np.sort(np.array(idx))
    return X.loc[idx], y.loc[idx]


# --------------------------------------------------------------------------- synthetic flows

# Environment traffic profile -> the NSL-KDD category it most resembles. This is how
# simulated flows become the alert classes the HMM observes.
PROFILE_TO_ALERT = {
    "benign": "normal", "Recon": "probe", "Weaponization": "normal", "Delivery": "r2l",
    "Exploitation": "u2r", "C2": "r2l", "Exfiltration": "dos",
}


def synthetic_flows(ticks: int = 400, seed: int = 0, env=None, restart_every: int = 60) -> pd.DataFrame:
    """Flows from the simulated network, one row per flow.

    Columns: the environment's flow features, then tick, src, dst, profile (the
    attacker's phase or "benign"), label (the alert category from PROFILE_TO_ALERT)
    and malicious. The attack restarts every `restart_every` ticks so every phase
    appears in a long run.
    """
    from ..core.environment import FEATURES, NetworkEnvironment

    env = env if env is not None else NetworkEnvironment(seed=seed)
    rows = []
    for t in range(ticks):
        if restart_every and t and t % restart_every == 0:
            env.seed = None if env.seed is None else env.seed + 1
            env.reset()
        env.step()
        phase = env.state.phase
        for flow in env.observe().flows:
            profile = phase if flow.malicious else "benign"
            rows.append({**{k: flow.features[k] for k in FEATURES}, "tick": t, "src": flow.src, "dst": flow.dst,
                         "profile": profile, "label": PROFILE_TO_ALERT[profile], "malicious": flow.malicious})
    return pd.DataFrame(rows)


def synthetic_xy(ticks: int = 400, seed: int = 0) -> Tuple[pd.DataFrame, pd.Series]:
    from ..core.environment import FEATURES

    df = synthetic_flows(ticks, seed)
    return df[FEATURES], df["label"]
