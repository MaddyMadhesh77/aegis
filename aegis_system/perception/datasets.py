"""Datasets for the perception layer.

NSL-KDD   the main dataset (run scripts/fetch_nsl_kdd.py once to download it into
          data/nsl_kdd/). Each record's attack name is mapped to one of the five
          standard categories: normal, dos, probe, r2l, u2r.
synthetic flows generated by the Phase 0 network environment, labelled with the
          attacker's true kill-chain phase; used by the closed-loop demo and by
          tests that must not depend on the download.
"""

